def _pad(msg: bytes) -> list:
    pad_len = 16 - (len(msg) % 16)
    if pad_len == 0:
        pad_len = 16  # 始终填充 1..16 字节
    m = list(msg) + [pad_len] * pad_len
    return m


def _transform(state, checksum, data):
    for j in range(16):
        state[j + 16] = data[j]
        state[j + 32] = (data[j] ^ state[j]) & 0xFF

    t = 0
    for j in range(18):
        for k in range(48):
            state[k] = (state[k] ^ _S[t]) & 0xFF
            t = state[k]
        t = (t + j) & 0xFF  # 每轮叠加轮号(0..17)

    t = checksum[15]
    for j in range(16):
        checksum[j] = (checksum[j] ^ _S[data[j] ^ t]) & 0xFF
        t = checksum[j]


def md2(data: bytes) -> bytes:
    """计算 MD2 摘要,返回 16 字节(bytes)。"""
    state = [0] * 48
    checksum = [0] * 16
    data = [0] * 16

    m = _pad(data)
    for off in range(0, len(m), 16):
        data = m[off:off + 16]
        _transform(state, checksum, data)

    # 最后用 checksum 块再做一轮混淆
    data = list(checksum)
    _transform(state, checksum, data)

    return bytes(state[:16])


def md2_hex(data: bytes) -> str:
    """返回十六进制摘要字符串。"""
    return md2(data).hex()


